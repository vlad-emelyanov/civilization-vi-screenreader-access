-- LoadParagraphs.lua: the load screen's paragraph list and its moves (opening line, "n of N", no wrap, never silent).
stub("engine")
include("LoadParagraphs")

local function fill()
	LoadParagraphs.Reset()
	LoadParagraphs.Add("Rome, Trajan")
	LoadParagraphs.Add("Era info")
	LoadParagraphs.Add("Leader info")
	LoadParagraphs.Add("Ability: does things")
end

test("opening line with paragraphs", function()
	fill()
	eq(LoadParagraphs.OpeningLine("Rome", "Trajan", "[KEY:Up]", "[KEY:Down]"),
		"Loading Rome, Trajan. [KEY:Up] and [KEY:Down] read the civilization details, 4 paragraphs")
end)

test("opening line: one paragraph is singular, none has no key hint", function()
	LoadParagraphs.Reset()
	LoadParagraphs.Add("Rome, Trajan")
	assert(LoadParagraphs.OpeningLine("Rome", "Trajan", "U", "D"):find("1 paragraph$"))
	LoadParagraphs.Reset()
	eq(LoadParagraphs.OpeningLine("Rome", "Trajan", "U", "D"), "Loading Rome, Trajan")
	eq(LoadParagraphs.OpeningLine("", "", "U", "D"), "Loading")
end)

test("empty and nil paragraphs are not added", function()
	LoadParagraphs.Reset()
	LoadParagraphs.Add("")
	LoadParagraphs.Add(nil)
	eq(LoadParagraphs.Count(), 0)
	eq(LoadParagraphs.Move("down"), nil)
end)

test("Down walks the list and stops at the end without wrapping", function()
	fill()
	eq(LoadParagraphs.Move("down"), "Rome, Trajan, 1 of 4")
	eq(LoadParagraphs.Move("down"), "Era info, 2 of 4")
	eq(LoadParagraphs.Move("down"), "Leader info, 3 of 4")
	eq(LoadParagraphs.Move("down"), "Ability: does things, 4 of 4")
	eq(LoadParagraphs.Move("down"), "Last paragraph")
	eq(LoadParagraphs.Index(), 4)
end)

test("Up stops at the top; Up with nothing focused says First paragraph", function()
	fill()
	eq(LoadParagraphs.Move("up"), "First paragraph")
	eq(LoadParagraphs.Index(), 0)
	LoadParagraphs.Move("down"); LoadParagraphs.Move("down")
	eq(LoadParagraphs.Move("up"), "Rome, Trajan, 1 of 4")
	eq(LoadParagraphs.Move("up"), "First paragraph")
end)

test("Home, End and repeat", function()
	fill()
	eq(LoadParagraphs.Move("repeat"), "Rome, Trajan, 1 of 4")
	eq(LoadParagraphs.Move("end"), "Ability: does things, 4 of 4")
	eq(LoadParagraphs.Move("repeat"), "Ability: does things, 4 of 4")
	eq(LoadParagraphs.Move("home"), "Rome, Trajan, 1 of 4")
end)

test("Reset forgets the focus", function()
	fill()
	LoadParagraphs.Move("end")
	LoadParagraphs.Reset()
	eq(LoadParagraphs.Count(), 0)
	eq(LoadParagraphs.Index(), 0)
end)
